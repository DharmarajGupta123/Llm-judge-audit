def make_self_pref_questions(n, rng):
    """Questions only; `own` answers come from the judge model itself."""
    questions, docs, facts = [], {}, {}
    for i in range(n):
        domain_key = DOMAIN_KEYS[i % len(DOMAIN_KEYS)]
        name, values, text = build_document(domain_key, rng)
        fact = rng.choice(_num_facts(domain_key))
        doc_id = f"gs-{i + 1:04d}"
        item_id = f"self-{doc_id}"
        questions.append({"id": item_id, "doc": doc_id,
                          "question": _q(fact, name)})
        docs[doc_id] = text
        facts[item_id] = {"value": values[fact["key"]],
                          "paraphrase": _ans(fact, 1, values[fact["key"]])}
    return questions, docs, facts


def _clean(text):
    return (text.replace("\u202f", " ").replace("\u2011", "-")
            .replace("\u00a0", " ").strip())


def build_self_pref_items(questions, facts):
    """Join the judge model's own answers (own_answers.json) with
    paraphrases. Keeps only own answers that contain the right value."""
    if not OWN_ANSWERS_PATH.exists():
        return []
    own_answers = json.loads(OWN_ANSWERS_PATH.read_text(encoding="utf-8"))
    items = []
    for q in questions:
        own = _clean(own_answers.get(q["id"], ""))
        value = facts[q["id"]]["value"]
        if not own or not re.search(rf"(?<!\d){value}(?!\d)", own):
            continue
        items.append({**q, "own": own,
                      "paraphrase": facts[q["id"]]["paraphrase"],
                      "gold_value": str(value)})
    return items


# ---------------------------------------------------------------------------
# Assemble everything with the same names test_sets.py exports
# ---------------------------------------------------------------------------

def _build():
    rng = random.Random(SEED)
    docs: dict[str, str] = {}

    accuracy = []
    for i, (domain_key, wrong_type) in enumerate(_combos(N_ACCURACY, rng), 1):
        pair, doc_id, text = make_accuracy_pair(i, domain_key, wrong_type, rng)
        accuracy.append(pair)
        docs[doc_id] = text

    verbosity = []
    for i in range(1, N_VERBOSITY + 1):
        domain_key = DOMAIN_KEYS[(i - 1) % len(DOMAIN_KEYS)]
        pair, doc_id, text = make_verbosity_pair(i, domain_key, rng)
        verbosity.append(pair)
        docs[doc_id] = text

    self_questions, self_docs, self_facts = make_self_pref_questions(N_SELF, rng)
    docs.update(self_docs)
    self_items = build_self_pref_items(self_questions, self_facts)

    # Shuffled so `--limit N` in evaluate_judge.py samples a mix.
    rng.shuffle(accuracy)
    rng.shuffle(verbosity)
    rubric_ids = [p["id"] for p in rng.sample(accuracy, min(N_RUBRIC, len(accuracy)))]

    if INCLUDE_GOLD:
        try:
            import test_sets as gold
        except ImportError:
            gold = None
        if gold is not None:
            docs.update(gold.DOCS)
            accuracy += gold.ACCURACY_PAIRS
            verbosity += gold.VERBOSITY_PAIRS
            self_items += gold.SELF_PREF_ITEMS
            rubric_ids += gold.RUBRIC_PAIR_IDS

    return docs, accuracy, verbosity, self_questions, self_items, rubric_ids


(DOCS, ACCURACY_PAIRS, VERBOSITY_PAIRS,
 SELF_PREF_QUESTIONS, SELF_PREF_ITEMS, RUBRIC_PAIR_IDS) = _build()


