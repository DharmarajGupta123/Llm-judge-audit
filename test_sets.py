def _draw_values(domain, rng):
    """Random value per numeric fact; values inside a group are distinct."""
    values: dict[str, int] = {}
    used_by_group: dict[str, set] = {}
    for fact in domain["facts"]:
        if fact["kind"] != "num":
            continue
        choices = list(range(fact["lo"], fact["hi"] + 1, fact["step"]))
        group = fact["group"]
        taken = used_by_group.setdefault(group, set())
        free = [c for c in choices if c not in taken]
        v = rng.choice(free or choices)
        taken.add(v)
        values[fact["key"]] = v
    return values


def build_document(domain_key, rng):
    """Return (name, values, document_text) for one fresh document."""
    domain = DOMAINS[domain_key]
    name = domain["name_fn"](rng)
    values = _draw_values(domain, rng)
    sentences = []
    for fact in domain["facts"]:
        if fact["kind"] == "num":
            sentences.append(fact["sentence"].format(v=values[fact["key"]]))
        else:
            sentences.append(fact["sentence"])
    sentences += rng.sample(domain["noise"], k=rng.randint(1, 2))
    rng.shuffle(sentences)
    text = f"{name} {domain['title']}. " + " ".join(sentences)
    return name, values, text


def _q(fact, name):
    return fact["q"].format(name=name)


def _ans(fact, idx, v):
    return fact["answers"][idx].format(v=v)


def _other_value(fact, values, rng):
    """A wrong number for the same fact (never the true one)."""
    choices = [c for c in range(fact["lo"], fact["hi"] + 1, fact["step"])
               if c != values[fact["key"]]]
    return rng.choice(choices)


def _num_facts(domain):
    return [f for f in DOMAINS[domain]["facts"] if f["kind"] == "num"]


def _bool_facts(domain):
    return [f for f in DOMAINS[domain]["facts"] if f["kind"] == "bool"]


# ---------------------------------------------------------------------------
# Accuracy pairs
# ---------------------------------------------------------------------------

def make_accuracy_pair(index, domain_key, wrong_type, rng):
    name, values, text = build_document(domain_key, rng)
    domain = DOMAINS[domain_key]
    doc_id = f"g-{index:04d}"
    pair = {"id": f"acc-{doc_id}-{wrong_type}", "doc": doc_id,
            "type": wrong_type, "gold_value": None}

    if wrong_type == "wrongnum":
        fact = rng.choice(_num_facts(domain_key))
        v = values[fact["key"]]
        pair.update(question=_q(fact, name), correct=_ans(fact, 0, v),
                    wrong=_ans(fact, 0, _other_value(fact, values, rng)),
                    gold_value=str(v))

    elif wrong_type == "swapctx":
        candidates = []
        for fact in _num_facts(domain_key):
            mates = [m for m in _num_facts(domain_key)
                     if m["group"] == fact["group"] and m["key"] != fact["key"]]
            if mates:
                candidates.append((fact, mates))
        fact, mates = rng.choice(candidates)
        mate = rng.choice(mates)
        v = values[fact["key"]]
        pair.update(question=_q(fact, name), correct=_ans(fact, 0, v),
                    wrong=_ans(fact, 0, values[mate["key"]]),
                    gold_value=str(v))

    elif wrong_type == "addition":
        fact = rng.choice(domain["facts"])
        if fact["kind"] == "num":
            v = values[fact["key"]]
            correct, gold = _ans(fact, 0, v), str(v)
        else:
            correct, gold = fact["correct"], None
        pair.update(question=_q(fact, name), correct=correct,
                    wrong=correct + " " + rng.choice(domain["extras"]),
                    gold_value=gold)

    elif wrong_type == "opposite":
        fact = rng.choice(_bool_facts(domain_key))
        pair.update(question=_q(fact, name), correct=fact["correct"],
                    wrong=fact["wrong"])

    elif wrong_type == "unanswer":
        q, wrong_tpl, lo, hi = rng.choice(domain["unanswerable"])
        pair.update(question=q.format(name=name),
                    correct=UNANSWERABLE_CORRECT,
                    wrong=wrong_tpl.format(n=rng.randint(lo, hi), name=name))
    else:
        raise ValueError(wrong_type)

    return pair, doc_id, text


def _combos(n, rng):
    """n (domain, wrong_type) combos, balanced across both axes."""
    combos: list[tuple[str, str]] = []
    while len(combos) < n:
        cycle = [(d, t) for t in WRONG_TYPES for d in DOMAIN_KEYS]
        rng.shuffle(cycle)
        combos.extend(cycle)
    return combos[:n]


# ---------------------------------------------------------------------------
# Verbosity pairs
# ---------------------------------------------------------------------------

def make_verbosity_pair(index, domain_key, rng):
    name, values, text = build_document(domain_key, rng)
    fact = rng.choice(_num_facts(domain_key))
    v = values[fact["key"]]
    wrong_answer = _ans(fact, 0, _other_value(fact, values, rng))
    openers = rng.sample(OPENERS, 3)
    long_wrong = " ".join(
        [o.format(s=name) for o in openers]
        + [rng.choice(MIDDLES).format(s=name)]
        + ["To answer your question directly: " + wrong_answer]
        + [c.format(s=name) for c in rng.sample(CLOSERS, 2)])
    doc_id = f"gv-{index:04d}"
    pair = {"id": f"verb-{doc_id}", "doc": doc_id, "type": "verbosity",
            "question": _q(fact, name),
            "short_correct": fact["short"].format(v=v),
            "long_wrong": long_wrong, "gold_value": str(v)}
    return pair, doc_id, text


