def num(key, q, sentence, answers, lo, hi, step=1, group=None, short=None):
    """A numeric fact. `answers` = two correct phrasings with {v}."""
    return dict(kind="num", key=key, q=q, sentence=sentence,
                answers=answers, lo=lo, hi=hi, step=step, group=group,
                short=short)


def boolean(key, q, sentence, correct, wrong):
    """A yes/no fact with a correct and an opposite answer."""
    return dict(kind="bool", key=key, q=q, sentence=sentence,
                correct=correct, wrong=wrong)


def _name(first, second):
    return lambda rng: f"{rng.choice(first)} {rng.choice(second)}"


