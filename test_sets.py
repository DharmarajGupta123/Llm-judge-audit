"""Procedurally generated test sets with KNOWN-correct winners.

Drop-in replacement for test_sets.py. It exports the same names
(DOCS, ACCURACY_PAIRS, VERBOSITY_PAIRS, SELF_PREF_QUESTIONS,
SELF_PREF_ITEMS, RUBRIC_PAIR_IDS), so evaluate_judge.py only needs its
import line changed.

Why generate instead of download: every document is built from random
company names and random numbers, so no model can have seen it in
training (no benchmark contamination). The correct answer is the value
that was inserted, so the winner is known by construction.

Wrong-answer types (the id of every accuracy pair ends with its type,
so results can be grouped by type afterwards):
  wrongnum   a different number for the asked fact
  swapctx    a REAL number from the same document, but for another fact
  addition   the correct answer plus one invented, unsupported claim
  opposite   the opposite yes/no claim
  unanswer   question the document cannot answer; correct = "not stated"

Everything is seeded, so the same seed gives the same data.

Settings (environment variables, all optional):
  JUDGE_SEED          default 2026
  JUDGE_N_ACCURACY    default 80   (pairs; each is judged twice)
  JUDGE_N_VERBOSITY   default 40
  JUDGE_N_SELF        default 12
  JUDGE_N_RUBRIC      default 12   (generated pairs, on top of the gold ones)
  JUDGE_INCLUDE_GOLD  default 1    (append the original handwritten set)

Self-preference needs the judge model's OWN answers. Create them with:
    python3 test_sets_generated.py --make-own-answers
which writes own_answers.json. Until that file exists, the generated
self-preference set is empty (the handwritten gold items still run).
"""

